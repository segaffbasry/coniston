"""Splits Coniston's own vector logo into parts the preloader can animate.

Source: the inline <svg width="220" height="40"> in the live site header (saved as _scrape/logo-live.svg). It has two
paths, both written in absolute commands only (M L H V C Z):
  path 1  the wordmark "Coniston": 11 closed sub-paths (C, o + counter, n, i + dot, s, t, o + counter, n)
  path 2  the mark: a ring of 30 short ticks with a gap on the right, the "C" set top-right of the wordmark
Sub-paths of the wordmark are grouped into 8 letters by horizontal overlap (a counter or a dot overlaps its letter).
Ticks are sorted clockwise round the ring's centre, starting from the tick just below the gap, so the preloader can
draw the ring the way a pen would. Writes lib/logo.ts.
Usage: python3 scripts/logo.py
"""
import math, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "_scrape", "logo-live.svg")
OUT = os.path.join(HERE, "..", "lib", "logo.ts")


def subpaths(d):
    return [s.strip() for s in re.findall(r"M[^M]*", d)]


def bbox(sp):
    xs, ys, x, y = [], [], 0.0, 0.0
    for cmd, args in re.findall(r"([MLHVCZ])([^MLHVCZ]*)", sp):
        n = [float(a) for a in re.findall(r"-?\d*\.?\d+(?:e-?\d+)?", args)]
        if cmd in "MLC":
            for i in range(0, len(n), 2):
                x, y = n[i], n[i + 1]; xs.append(x); ys.append(y)
        elif cmd == "H":
            for v in n: x = v; xs.append(x); ys.append(y)
        elif cmd == "V":
            for v in n: y = v; xs.append(x); ys.append(y)
    return min(xs), min(ys), max(xs), max(ys)


def main():
    svg = open(SRC).read()
    word, mark = re.findall(r'<path[^>]*?d="([^"]+)"', svg)[:2]

    parts = sorted(((bbox(s), s) for s in subpaths(word)), key=lambda p: p[0][0])
    letters = []
    for box, s in parts:
        if letters and box[0] < letters[-1]["box"][2] - 0.5:  # overlaps the previous letter: a counter or a dot
            prev = letters[-1]
            prev["d"] += s
            prev["box"] = (min(prev["box"][0], box[0]), min(prev["box"][1], box[1]), max(prev["box"][2], box[2]), max(prev["box"][3], box[3]))
        else:
            letters.append({"d": s, "box": box})

    ticks = [(bbox(s), s) for s in subpaths(mark)]
    xs = [b[0] for b, _ in ticks] + [b[2] for b, _ in ticks]
    ys = [b[1] for b, _ in ticks] + [b[3] for b, _ in ticks]
    # The ring is open on the right, so its centre sits one radius (half the height) in from the left edge.
    cy = (min(ys) + max(ys)) / 2
    cx = min(xs) + (max(ys) - min(ys)) / 2
    # The gap sits on the right (angle 0). Clockwise on screen = increasing atan2 with y down; start just below it.
    ang = lambda b: math.atan2((b[1] + b[3]) / 2 - cy, (b[0] + b[2]) / 2 - cx) % (2 * math.pi)
    ticks.sort(key=lambda t: ang(t[0]))
    mark_box = (min(xs), min(ys), max(xs), max(ys))

    f = lambda v: f"{v:.2f}".rstrip("0").rstrip(".")
    lines = [
        "// Generated by scripts/logo.py from the live header logo (conistonltd.co.uk). Do not edit by hand.",
        "// Wordmark letters left to right; the mark's 30 ticks clockwise from just below the gap.",
        'export const LOGO_VIEWBOX = "0 0 220 40";',
        f"export const MARK_CENTRE = {{ x: {f(cx)}, y: {f(cy)} }};",
        f"export const MARK_BOX = {{ x: {f(mark_box[0])}, y: {f(mark_box[1])}, w: {f(mark_box[2] - mark_box[0])}, h: {f(mark_box[3] - mark_box[1])} }};",
        f"export const WORD_BOX = {{ x: {f(letters[0]['box'][0])}, y: {f(min(l['box'][1] for l in letters))}, w: {f(letters[-1]['box'][2] - letters[0]['box'][0])}, h: {f(max(l['box'][3] for l in letters) - min(l['box'][1] for l in letters))} }};",
        "export const LETTERS: string[] = [",
        *[f'  "{l["d"]}",' for l in letters],
        "];",
        "export const TICKS: string[] = [",
        *[f'  "{s}",' for _, s in ticks],
        "];",
        "",
    ]
    open(OUT, "w").write("\n".join(lines))
    print(f"{len(letters)} letters, {len(ticks)} ticks, mark centre {cx:.2f},{cy:.2f}, mark box {mark_box}")


if __name__ == "__main__":
    main()
